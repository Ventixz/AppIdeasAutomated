/*
 * whiteboard-core.js — the whole whiteboard engine, with no DOM, no canvas
 * creation, no network. It is pure data + geometry, so it runs and is tested
 * under Node, and the browser app (script.js) is a thin shell over it.
 *
 * Three ideas live here:
 *
 *   1. A whiteboard is a DOCUMENT, not a bitmap. Everything you draw is stored
 *      as vector elements (strokes with their points, shapes, text notes). You
 *      can re-render it at any resolution, undo it, hit-test it, and export it
 *      to real SVG. Saving `canvas.toDataURL()` would throw all of that away.
 *
 *   2. Freehand strokes are smoothed with MIDPOINT QUADRATIC BÉZIERS, not drawn
 *      as straight segments between raw points. The canvas drawing and the SVG
 *      `d` string are generated by the same algorithm, so what you export is
 *      pixel-for-curve identical to what you see.
 *
 *   3. Collaboration is conflict-free. Each editor is a REPLICA with a Lamport
 *      clock; every edit is an immutable operation in an append-only log. The
 *      visible document is a PURE FUNCTION of the set of operations, ordered by
 *      (lamport, siteId). Two replicas that have seen the same operations — in
 *      any order, with any duplicates — always compute the identical document.
 *      That is the convergence property a real multi-user board needs, and it
 *      is what tests.js checks by shuffling delivery order.
 *
 * The transport is deliberately absent: feed operations between replicas over
 * BroadcastChannel (what the browser app does, so tabs collaborate with no
 * server), a WebSocket, or a file — the engine does not care.
 */
(function (root, factory) {
  'use strict';
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Whiteboard = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* ------------------------------------------------------------------ *
   * Geometry helpers
   * ------------------------------------------------------------------ */

  function midpoint(a, b) {
    return { x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 };
  }

  // Shortest distance from point (px,py) to the segment a-b. The routine the
  // eraser's hit-testing is built on; textbook projection-onto-segment, clamped.
  function pointSegmentDistance(px, py, ax, ay, bx, by) {
    const vx = bx - ax, vy = by - ay;
    const wx = px - ax, wy = py - ay;
    const len2 = vx * vx + vy * vy;
    let t = len2 === 0 ? 0 : (wx * vx + wy * vy) / len2;
    if (t < 0) t = 0; else if (t > 1) t = 1;
    const cx = ax + t * vx, cy = ay + t * vy;
    return Math.hypot(px - cx, py - cy);
  }

  // Round to 2 dp for compact, stable serialization and SVG output.
  function r(n) { return Math.round(n * 100) / 100; }

  /* ------------------------------------------------------------------ *
   * Stroke smoothing — the one algorithm, used for both canvas and SVG
   *
   * Raw pointer samples are a jagged polyline. Joining them with lineTo shows
   * every corner. Instead we draw a quadratic curve through the MIDPOINT of
   * each pair of samples, using the sample itself as the control point. The
   * curve passes smoothly through every midpoint and bends toward every sample,
   * turning a noisy polyline into a continuous, natural-looking stroke.
   *
   * drawSmoothPath (canvas) and pathD (SVG) implement the SAME construction so
   * the two never drift apart.
   * ------------------------------------------------------------------ */

  function drawSmoothPath(ctx, points) {
    const n = points.length;
    if (n === 0) return;
    if (n === 1) {
      // A single tap: draw a dot (a zero-length line with a round cap shows up).
      ctx.moveTo(points[0].x, points[0].y);
      ctx.lineTo(points[0].x + 0.01, points[0].y);
      return;
    }
    ctx.moveTo(points[0].x, points[0].y);
    if (n === 2) { ctx.lineTo(points[1].x, points[1].y); return; }
    let i;
    for (i = 1; i < n - 2; i++) {
      const c = midpoint(points[i], points[i + 1]);
      ctx.quadraticCurveTo(points[i].x, points[i].y, c.x, c.y);
    }
    // Final segment runs the curve out to the very last sample.
    ctx.quadraticCurveTo(points[i].x, points[i].y, points[i + 1].x, points[i + 1].y);
  }

  function pathD(points) {
    const n = points.length;
    if (n === 0) return '';
    if (n === 1) return 'M ' + r(points[0].x) + ' ' + r(points[0].y) + ' l 0.01 0';
    let d = 'M ' + r(points[0].x) + ' ' + r(points[0].y);
    if (n === 2) return d + ' L ' + r(points[1].x) + ' ' + r(points[1].y);
    let i;
    for (i = 1; i < n - 2; i++) {
      const c = midpoint(points[i], points[i + 1]);
      d += ' Q ' + r(points[i].x) + ' ' + r(points[i].y) + ' ' + r(c.x) + ' ' + r(c.y);
    }
    d += ' Q ' + r(points[i].x) + ' ' + r(points[i].y) + ' ' + r(points[i + 1].x) + ' ' + r(points[i + 1].y);
    return d;
  }

  // What the naive whiteboard draws — kept so the demo and docs can show the
  // difference. Straight lines between every raw sample: visibly polygonal.
  function pathDNaive(points) {
    if (!points.length) return '';
    let d = 'M ' + r(points[0].x) + ' ' + r(points[0].y);
    for (let i = 1; i < points.length; i++) d += ' L ' + r(points[i].x) + ' ' + r(points[i].y);
    return d;
  }

  /* ------------------------------------------------------------------ *
   * Elements — the vector primitives a document is made of
   * ------------------------------------------------------------------ */

  // Normalize a rect/ellipse's two corners to {x, y, w, h} with w,h >= 0.
  function boxOf(el) {
    const x = Math.min(el.a.x, el.b.x), y = Math.min(el.a.y, el.b.y);
    return { x: x, y: y, w: Math.abs(el.b.x - el.a.x), h: Math.abs(el.b.y - el.a.y) };
  }

  // Axis-aligned bounding box of one element, in document coordinates.
  function elementBounds(el) {
    switch (el.type) {
      case 'pen':
      case 'highlighter': {
        let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
        for (const p of el.points) {
          if (p.x < minX) minX = p.x; if (p.y < minY) minY = p.y;
          if (p.x > maxX) maxX = p.x; if (p.y > maxY) maxY = p.y;
        }
        const pad = (el.width || 1) / 2;
        return { x: minX - pad, y: minY - pad, w: (maxX - minX) + 2 * pad, h: (maxY - minY) + 2 * pad };
      }
      case 'line': {
        const pad = (el.width || 1) / 2;
        const x = Math.min(el.a.x, el.b.x), y = Math.min(el.a.y, el.b.y);
        return { x: x - pad, y: y - pad, w: Math.abs(el.b.x - el.a.x) + 2 * pad, h: Math.abs(el.b.y - el.a.y) + 2 * pad };
      }
      case 'rect':
      case 'ellipse': {
        const b = boxOf(el); const pad = (el.width || 1) / 2;
        return { x: b.x - pad, y: b.y - pad, w: b.w + 2 * pad, h: b.h + 2 * pad };
      }
      case 'text': {
        const fs = el.fontSize || 16;
        const w = (el.text ? el.text.length : 1) * fs * 0.6;
        return { x: el.x, y: el.y - fs, w: w, h: fs * 1.3 };
      }
      default:
        return { x: 0, y: 0, w: 0, h: 0 };
    }
  }

  // Bounding box of a whole document (array of elements). Null if empty.
  function documentBounds(doc) {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const el of doc) {
      const b = elementBounds(el);
      if (b.w === 0 && b.h === 0 && el.type !== 'text') continue;
      if (b.x < minX) minX = b.x; if (b.y < minY) minY = b.y;
      if (b.x + b.w > maxX) maxX = b.x + b.w; if (b.y + b.h > maxY) maxY = b.y + b.h;
    }
    if (minX === Infinity) return null;
    return { x: minX, y: minY, w: maxX - minX, h: maxY - minY };
  }

  /* ------------------------------------------------------------------ *
   * Hit testing — used by the eraser
   *
   * Returns the ids of every element within `radius` of (x,y). Strokes and
   * lines use true point-to-segment distance; shapes and text use proximity to
   * their bounding box. Honest and good enough for an eraser.
   * ------------------------------------------------------------------ */

  function distanceToElement(x, y, el) {
    switch (el.type) {
      case 'pen':
      case 'highlighter': {
        const pts = el.points;
        if (pts.length === 1) return Math.hypot(x - pts[0].x, y - pts[0].y);
        let best = Infinity;
        for (let i = 0; i < pts.length - 1; i++) {
          const d = pointSegmentDistance(x, y, pts[i].x, pts[i].y, pts[i + 1].x, pts[i + 1].y);
          if (d < best) best = d;
        }
        return Math.max(0, best - (el.width || 1) / 2);
      }
      case 'line':
        return Math.max(0, pointSegmentDistance(x, y, el.a.x, el.a.y, el.b.x, el.b.y) - (el.width || 1) / 2);
      case 'rect':
      case 'ellipse':
      case 'text': {
        const b = elementBounds(el);
        const dx = Math.max(b.x - x, 0, x - (b.x + b.w));
        const dy = Math.max(b.y - y, 0, y - (b.y + b.h));
        return Math.hypot(dx, dy);
      }
      default:
        return Infinity;
    }
  }

  function hitTest(doc, x, y, radius) {
    const ids = [];
    for (const el of doc) {
      if (distanceToElement(x, y, el) <= radius) ids.push(el.id);
    }
    return ids;
  }

  /* ------------------------------------------------------------------ *
   * The replica / operation log — where convergence comes from
   *
   * An operation is immutable: { kind, id, lamport, site, ... }.
   *   - add   : { el }          add an element (el.id === op.id)
   *   - del   : { target }      tombstone an element by id
   *   - clear : {}              hide everything created at or before this op
   *
   * ordering key = (lamport, site). Elements render in that order; it is also
   * how concurrent clears and deletes are resolved deterministically. Because
   * the document is computed from the *set* of ops with a *total order*, every
   * replica converges regardless of the order ops arrive in.
   * ------------------------------------------------------------------ */

  function compareOrder(a, b) {
    if (a.lamport !== b.lamport) return a.lamport - b.lamport;
    if (a.site < b.site) return -1;
    if (a.site > b.site) return 1;
    return 0;
  }

  function createReplica(siteId) {
    if (!siteId) siteId = 'site-' + Math.random().toString(36).slice(2, 8);
    let clock = 0;
    const ops = [];
    const seen = new Set();           // opId -> dedup
    let cache = null;                 // memoized document
    let cacheLen = -1;

    function nextOp(kind, extra) {
      clock += 1;
      const op = Object.assign({ kind: kind, id: siteId + '@' + clock, lamport: clock, site: siteId }, extra);
      ingest(op);
      return op;
    }

    // Apply one op (local or remote). Idempotent: duplicates are ignored, so
    // a flaky transport that re-delivers is harmless.
    function ingest(op) {
      if (seen.has(op.id)) return false;
      seen.add(op.id);
      ops.push(op);
      if (op.lamport > clock) clock = op.lamport;   // Lamport merge rule
      cache = null;
      return true;
    }

    function document() {
      if (cache && cacheLen === ops.length) return cache;
      const sorted = ops.slice().sort(compareOrder);
      const deleted = new Set();
      let clearMax = null;
      for (const op of sorted) {
        if (op.kind === 'del') deleted.add(op.target);
        else if (op.kind === 'clear') {
          if (!clearMax || compareOrder(op, clearMax) > 0) clearMax = op;
        }
      }
      const els = [];
      for (const op of sorted) {
        if (op.kind !== 'add') continue;
        if (deleted.has(op.el.id)) continue;
        if (clearMax && compareOrder(op, clearMax) <= 0) continue;
        els.push(op.el);
      }
      cache = els; cacheLen = ops.length;
      return els;
    }

    return {
      site: siteId,
      get clock() { return clock; },
      get opCount() { return ops.length; },

      // --- local edits: build an element, return the op to broadcast ---
      addElement: function (el) {
        return nextOp('add', { el: Object.assign({}, el, { id: siteId + '@' + (clock + 1) }) });
      },
      deleteElement: function (id) { return nextOp('del', { target: id }); },
      clear: function () { return nextOp('clear', {}); },

      // --- remote edits: feed in an op from another replica ---
      receive: function (op) { return ingest(op); },

      // --- read the current board ---
      document: document,

      // --- full snapshot (for "save" / initial sync of a new peer) ---
      snapshot: function () { return { site: siteId, ops: ops.slice() }; },
      loadSnapshot: function (snap) {
        for (const op of snap.ops) ingest(op);
        return document();
      }
    };
  }

  /* ------------------------------------------------------------------ *
   * Rendering a document onto a 2D context
   * ------------------------------------------------------------------ */

  function renderDocument(ctx, doc, opts) {
    opts = opts || {};
    if (opts.background) {
      ctx.save();
      ctx.fillStyle = opts.background;
      ctx.fillRect(0, 0, opts.width || 0, opts.height || 0);
      ctx.restore();
    }
    for (const el of doc) drawElement(ctx, el);
  }

  function drawElement(ctx, el) {
    ctx.save();
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    ctx.globalAlpha = el.opacity == null ? 1 : el.opacity;
    ctx.strokeStyle = el.color || '#111';
    ctx.lineWidth = el.width || 2;
    switch (el.type) {
      case 'pen':
      case 'highlighter':
        ctx.beginPath();
        drawSmoothPath(ctx, el.points);
        ctx.stroke();
        break;
      case 'line':
        ctx.beginPath();
        ctx.moveTo(el.a.x, el.a.y);
        ctx.lineTo(el.b.x, el.b.y);
        ctx.stroke();
        break;
      case 'rect': {
        const b = boxOf(el);
        if (el.fill) { ctx.fillStyle = el.fill; ctx.fillRect(b.x, b.y, b.w, b.h); }
        ctx.strokeRect(b.x, b.y, b.w, b.h);
        break;
      }
      case 'ellipse': {
        const b = boxOf(el);
        ctx.beginPath();
        ctx.ellipse(b.x + b.w / 2, b.y + b.h / 2, b.w / 2, b.h / 2, 0, 0, Math.PI * 2);
        if (el.fill) { ctx.fillStyle = el.fill; ctx.fill(); }
        ctx.stroke();
        break;
      }
      case 'text':
        ctx.fillStyle = el.color || '#111';
        ctx.font = (el.fontSize || 16) + 'px ' + (el.fontFamily || 'system-ui, sans-serif');
        ctx.textBaseline = 'alphabetic';
        for (const [i, line] of String(el.text || '').split('\n').entries()) {
          ctx.fillText(line, el.x, el.y + i * (el.fontSize || 16) * 1.3);
        }
        break;
    }
    ctx.restore();
  }

  /* ------------------------------------------------------------------ *
   * SVG export — real vector output, same curves as the canvas
   * ------------------------------------------------------------------ */

  function escapeXml(s) {
    return String(s).replace(/[<>&"']/g, function (c) {
      return { '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function elementToSvg(el) {
    const stroke = el.color || '#111';
    const w = el.width || 2;
    const op = el.opacity == null ? '' : ' opacity="' + el.opacity + '"';
    switch (el.type) {
      case 'pen':
      case 'highlighter':
        return '<path d="' + pathD(el.points) + '" fill="none" stroke="' + stroke +
          '" stroke-width="' + w + '" stroke-linecap="round" stroke-linejoin="round"' + op + '/>';
      case 'line':
        return '<line x1="' + r(el.a.x) + '" y1="' + r(el.a.y) + '" x2="' + r(el.b.x) + '" y2="' + r(el.b.y) +
          '" stroke="' + stroke + '" stroke-width="' + w + '" stroke-linecap="round"' + op + '/>';
      case 'rect': {
        const b = boxOf(el);
        return '<rect x="' + r(b.x) + '" y="' + r(b.y) + '" width="' + r(b.w) + '" height="' + r(b.h) +
          '" fill="' + (el.fill || 'none') + '" stroke="' + stroke + '" stroke-width="' + w + '"' + op + '/>';
      }
      case 'ellipse': {
        const b = boxOf(el);
        return '<ellipse cx="' + r(b.x + b.w / 2) + '" cy="' + r(b.y + b.h / 2) + '" rx="' + r(b.w / 2) +
          '" ry="' + r(b.h / 2) + '" fill="' + (el.fill || 'none') + '" stroke="' + stroke +
          '" stroke-width="' + w + '"' + op + '/>';
      }
      case 'text': {
        const fs = el.fontSize || 16;
        const lines = String(el.text || '').split('\n');
        return lines.map(function (line, i) {
          return '<text x="' + r(el.x) + '" y="' + r(el.y + i * fs * 1.3) + '" font-size="' + fs +
            '" font-family="system-ui, sans-serif" fill="' + stroke + '"' + op + '>' + escapeXml(line) + '</text>';
        }).join('');
      }
      default:
        return '';
    }
  }

  function toSVG(doc, opts) {
    opts = opts || {};
    const width = opts.width || (documentBounds(doc) ? Math.ceil(documentBounds(doc).x + documentBounds(doc).w + 20) : 800);
    const height = opts.height || (documentBounds(doc) ? Math.ceil(documentBounds(doc).y + documentBounds(doc).h + 20) : 600);
    const parts = ['<svg xmlns="http://www.w3.org/2000/svg" width="' + width + '" height="' + height +
      '" viewBox="0 0 ' + width + ' ' + height + '">'];
    if (opts.background) parts.push('<rect x="0" y="0" width="' + width + '" height="' + height + '" fill="' + opts.background + '"/>');
    for (const el of doc) parts.push(elementToSvg(el));
    parts.push('</svg>');
    return parts.join('\n');
  }

  /* ------------------------------------------------------------------ *
   * Document (de)serialization — this is what "save" really means
   * ------------------------------------------------------------------ */

  const FORMAT = 'whiteboard/vector';
  const VERSION = 1;

  function serialize(doc, meta) {
    return JSON.stringify({
      format: FORMAT, version: VERSION,
      meta: meta || {},
      elements: doc
    });
  }

  function deserialize(json) {
    const obj = typeof json === 'string' ? JSON.parse(json) : json;
    if (!obj || obj.format !== FORMAT) throw new Error('not a whiteboard document');
    if (!Array.isArray(obj.elements)) throw new Error('document has no elements array');
    return obj.elements;
  }

  /* ------------------------------------------------------------------ */

  return {
    // geometry / smoothing
    midpoint: midpoint,
    pointSegmentDistance: pointSegmentDistance,
    drawSmoothPath: drawSmoothPath,
    pathD: pathD,
    pathDNaive: pathDNaive,
    // elements
    elementBounds: elementBounds,
    documentBounds: documentBounds,
    boxOf: boxOf,
    hitTest: hitTest,
    distanceToElement: distanceToElement,
    // replica / collaboration
    createReplica: createReplica,
    compareOrder: compareOrder,
    // render + export
    renderDocument: renderDocument,
    drawElement: drawElement,
    toSVG: toSVG,
    // persistence
    serialize: serialize,
    deserialize: deserialize,
    FORMAT: FORMAT,
    VERSION: VERSION
  };
});
